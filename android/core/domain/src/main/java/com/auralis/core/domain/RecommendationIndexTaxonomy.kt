    val byId: Map<String, RecommendationTagDefinition> by lazy {
        definitions.associateBy { it.id }
    }

    val textualDimensions: Set<String> = setOf(
        "mood", "scene", "theme", "genre", "style", "vocal", "instrument", "texture", "rhythm",
    )

    fun definition(id: String): RecommendationTagDefinition? = byId[id]

    private val marks = Regex("\\p{M}+")
    private val separators = Regex("[\\s_-]+")
    private fun normalize(value: String): String = Normalizer.normalize(value, Normalizer.Form.NFKD)
        .replace(marks, "").lowercase(Locale.ROOT).replace(separators, " ").trim()

    private val byName: Map<String, List<RecommendationTagDefinition>> by lazy {
        definitions.flatMap { tag -> (listOf(tag.displayName) + tag.aliases).map { normalize(it) to tag } }
            .groupBy({ it.first }, { it.second }).mapValues { (_, tags) -> tags.distinctBy { it.id }.sortedBy { it.id } }
    }

    /** Ambiguous cross-dimension names require an explicit stable ID. */
    fun resolve(raw: String): RecommendationTagDefinition? = definition(raw.trim()) ?: byName[normalize(raw)]?.singleOrNull()

    fun search(query: String, limit: Int = 12): List<RecommendationTagDefinition> {
        val needle = normalize(query)
        if (needle.isEmpty()) return emptyList()
        val exact = byName[needle].orEmpty().map { it.id }.toSet()
        return definitions.mapNotNull { tag ->
            val display = normalize(tag.displayName)
            val id = normalize(tag.id)
            val score = when {
                tag.id in exact || id == needle -> 0
                display.startsWith(needle) || id.startsWith(needle) -> 1
                display.contains(needle) || id.contains(needle) -> 2
                tag.aliases.any { normalize(it).contains(needle) } -> 3
                else -> return@mapNotNull null
            }
            score to tag
        }.sortedWith(compareBy<Pair<Int, RecommendationTagDefinition>> { it.first }.thenBy { it.second.id })
            .take(limit.coerceIn(1, 50)).map { it.second }
    }

    fun isKnownTextTag(dimension: String, id: String): Boolean =
        dimension in textualDimensions && byId[id]?.dimension == dimension

    /** Compact prompt catalog: stable ID plus Chinese display name, without aliases. */
    fun compactCatalog(): String = definitions.joinToString(separator = "\n") { definition ->
        "${definition.id}=${definition.displayName}"
    }
